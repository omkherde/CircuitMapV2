/**
 * Get interpolated color from a colormap based on a normalized value.
 *
 * @param value - The value to map (will be normalized to 0-1 range)
 * @param range - [min, max] range for normalization
 * @param colormap - 'viridis' or 'inferno'
 * @returns RGB tuple [0-255, 0-255, 0-255]
 */
export function interpolateColormap(
  value: number,
  range: [number, number],
  colormap: 'viridis' | 'inferno' = 'viridis'
): RGB {
  const [min, max] = range;
  const colors = colormap === 'viridis' ? VIRIDIS : INFERNO;

  // Normalize value to 0-1
  const normalized = Math.max(0, Math.min(1, (value - min) / (max - min || 1)));

  // Get index in colormap
  const index = Math.floor(normalized * (colors.length - 1));

  return colors[index];
}

/**
 * Blend two RGB colors with alpha weighting.
 *
 * @param color1 - First RGB color
 * @param color2 - Second RGB color
 * @param alpha - Blend factor (0 = color1, 1 = color2)
 * @returns Blended RGB color
 */
export function blendColors(color1: RGB, color2: RGB, alpha: number): RGB {
  const a = Math.max(0, Math.min(1, alpha));
  return [
    Math.round(color1[0] * (1 - a) + color2[0] * a),
    Math.round(color1[1] * (1 - a) + color2[1] * a),
    Math.round(color1[2] * (1 - a) + color2[2] * a),
  ];
}

/**
 * Convert RGB to hex color string.
 */
export function rgbToHex(rgb: RGB): string {
  return `#${rgb.map((c) => c.toString(16).padStart(2, '0')).join('')}`;
}

/**
 * Convert RGB to normalized float array [0-1] for WebGL.
 */
export function rgbToFloat(rgb: RGB): [number, number, number] {
  return [rgb[0] / 255, rgb[1] / 255, rgb[2] / 255];
}
